const author = site.author;

function a(
  article: Omit<Article, "author" | "cover"> & { cover?: number },
  index: number,
): Article {
  return { ...article, author, cover: article.cover ?? index % 6 };
}

function finish(list: Array<Omit<Article, "author" | "cover">>): Article[] {
  return list.map((article, index) => ({ ...article, author, cover: index % 6 }));
}

